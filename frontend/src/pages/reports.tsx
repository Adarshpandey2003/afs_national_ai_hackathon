import { useEffect, useState } from 'react'
import { ArrowLeft, Play } from 'lucide-react'
import { api } from '../api'
import type { Report } from '../api/types'
import { Answer } from '../components/answer'
import { STATUS_COLOR, StatusBadge } from '../components/ui'
import { useData } from '../lib/data'
import { Link, navigate } from '../lib/router'
import { spot } from '../components/motion'
import { useRun } from '../lib/run'
import { draftStore } from '../lib/ui-state'

const day = (iso: string) => {
  const d = new Date(iso)
  return Number.isNaN(d.getTime()) ? '' : d.toLocaleDateString(undefined, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' })
}

export function ReportsPage() {
  const { cases, outputs, outputsLoaded, health } = useData()
  const byId = new Map(outputs.map((o) => [o.case_id, o]))
  const groups: [string, string, typeof cases][] = [
    ['Final evaluation', 'The six enquiries the jury evaluates.', cases.filter((c) => c.set === 'eval')],
    ['Development', 'The eight scenarios used while building the assistant.', cases.filter((c) => c.set === 'dev')],
  ]
  return (
    <div className="mx-auto w-full max-w-6xl px-5 pb-16 pt-8 lg:px-8">
      <h1 className="display text-[clamp(1.8rem,3vw,2.5rem)] leading-tight">Precomputed reports</h1>
      <p className="mt-2 max-w-[62ch] text-[16px] leading-relaxed text-ink-2">
        Answers generated by the assistant in batch mode and committed to the repository without edits. Open one to see its answer, or run any enquiry live.
      </p>
      {health.state === 'down' && <p className="mt-6 rounded-xl border border-bad/40 bg-bad-bg p-4 text-bad">The backend is unreachable, so the reports can’t be loaded.</p>}

      {groups.map(([title, intro, list]) => (
        <section key={title} aria-labelledby={`${title}-h`} className="mt-10">
          <h2 id={`${title}-h`} className="display text-[1.2rem]">{title}</h2>
          <p className="mt-1 text-[14px] text-ink-3">{intro}</p>
          <ul className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
            {list.map((c) => {
              const o = byId.get(c.case_id)
              return (
                <li key={c.case_id}>
                  {o ? (
                    <Link to={`/reports/${c.case_id}`} onMouseMove={spot} className="glass spotlight group relative flex h-full flex-col overflow-hidden p-5 pb-6 transition-colors hover:border-cyan/60">
                      <span className="display text-[1.6rem] leading-none text-cyan">{c.case_id}</span>
                      <span className="mt-2.5 font-semibold leading-snug group-hover:underline group-hover:underline-offset-2">{c.title}</span>
                      <span className="mt-auto flex flex-wrap items-center justify-between gap-2 pt-5">
                        <StatusBadge status={o.decision_status} />
                        <span className="text-[13px] text-ink-3">{day(o.generated_at)}</span>
                      </span>
                      <span aria-hidden className="absolute inset-x-0 bottom-0 h-1" style={{ background: STATUS_COLOR[o.decision_status] }} />
                    </Link>
                  ) : (
                    <div className="flex h-full flex-col rounded-[1.25rem] border border-dashed border-rule-strong p-5 text-ink-3">
                      <span className="display text-[1.6rem] leading-none">{c.case_id}</span>
                      <span className="mt-2.5 font-semibold leading-snug">{c.title}</span>
                      <span className="mt-auto pt-5 text-[13px]">{outputsLoaded ? 'Not generated yet' : 'Loading…'}</span>
                    </div>
                  )}
                </li>
              )
            })}
          </ul>
        </section>
      ))}
    </div>
  )
}

/** A precomputed report on the same board as a live run. */
export function ReportPage({ caseId }: { caseId: string }) {
  const { cases, health } = useData()
  const run = useRun()
  const ready = health.state === 'ok'
  const [state, setState] = useState<{ status: 'loading' | 'ok' | 'error'; report?: Report; error?: string }>({ status: 'loading' })

  useEffect(() => {
    if (!ready) return
    let cancelled = false
    setState({ status: 'loading' })
    api.output(caseId).then(
      (report) => !cancelled && setState({ status: 'ok', report }),
      (e: Error) => !cancelled && setState({ status: 'error', error: e.message }),
    )
    return () => { cancelled = true }
  }, [caseId, ready])

  const c = cases.find((x) => x.case_id === caseId)
  const enquiry = state.report?.enquiry || c?.text
  const runLive = () => {
    if (!enquiry) return
    run.reset()
    draftStore.set({ text: enquiry, caseId })
    navigate('/')
  }

  return (
    <div className="flex flex-1 flex-col">
      <div className="no-print mx-auto flex w-full max-w-[62rem] flex-wrap items-center gap-x-4 gap-y-2 px-4 pt-5 text-[14px] sm:px-6">
        <Link to="/reports" className="inline-flex items-center gap-1.5 font-semibold text-ink-2 hover:text-ink"><ArrowLeft size={16} aria-hidden /> All reports</Link>
        <span className="text-ink-3">Generated in batch mode and committed without edits.</span>
        {enquiry && (
          <button type="button" onClick={runLive} className="ml-auto inline-flex items-center gap-1.5 font-semibold text-ink-2 hover:text-ink">
            <Play size={15} aria-hidden /> Run this enquiry live
          </button>
        )}
      </div>
      {state.status === 'ok' && state.report ? (
        <div className="mx-auto w-full max-w-[62rem] px-4 pb-14 pt-5 sm:px-6">
          <Answer report={state.report} enquiry={enquiry} caseLabel={c ? `${c.case_id} – ${c.title}` : caseId} />
        </div>
      ) : state.status === 'error' ? (
        <p className="glass mx-auto mt-8 max-w-xl px-6 py-5 text-bad">{state.error}</p>
      ) : (
        <div className="mx-auto mt-5 w-full max-w-[62rem] px-6" aria-busy="true" aria-label="Loading the report">
          <div className="skeleton h-[32rem] rounded-[1.25rem]" />
        </div>
      )}
    </div>
  )
}
